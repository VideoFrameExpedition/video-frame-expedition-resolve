def test_a_gpu_run_starts_after_the_memory_check() -> None:
    vram = Vram(3000)
    result = fake("gpu_ok", vram=vram).transcribe(
        GPU_REQUEST, cancel=CancelToken(), progress=Recorder()
    )
    assert result.stats["device"] == "cuda"
    assert result.stats["visible"] == "0"  # the parent exposes GPU 0 to this child only
    assert result.stats["order"] == "PCI_BUS_ID"  # the card nvidia-smi calls 0
    assert result.stats["allocator"] == "cuda_malloc_async"
    assert result.stats["cuda_dll_dir"] == str(Path("C:/rt/cublas"))
    assert result.stats["vram_min_free_mib"] == 3000
    assert vram.reads >= 1


