def test_cancel_mid_run_leaves_no_process(tmp_path: Path) -> None:
    pid_file = tmp_path / "pids.json"
    cancel = CancelToken()
    progress = Recorder()

    def cancel_when_running() -> None:
        read_pids(pid_file)
        time.sleep(0.5)
        cancel.cancel("Annulé par le test")

    threading.Thread(target=cancel_when_running, daemon=True).start()
    with pytest.raises(CancelledError, match="Annulé par le test"):
        fake("slow", pid_file).transcribe(REQUEST, cancel=cancel, progress=progress)
    pids = read_pids(pid_file)
    assert pids["pid"] is not None
    assert gone(pids["pid"], within_s=2.0)
    assert pids["grandchild"] is not None
    assert gone(pids["grandchild"], within_s=2.0)
    assert progress.calls  # it was running


